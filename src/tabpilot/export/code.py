"""Render the bundle's `pipeline.py` from its Jinja2 template (PRD §22.4; FR-ART-02).

Every value placed in the template is a Python literal produced by `repr()` (strings, lists,
dicts) or by `codegen.estimator_source`, so user-derived names can never become code. The
template itself is fixed text in the repository; nothing is generated by an LLM.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from tabpilot.export.codegen import estimator_source

TEMPLATES = Path(__file__).parent / "templates"


THIRD_PARTY_PLAIN = ("import joblib", "import numpy as np", "import pandas as pd")


def render_pipeline(
    model: Any,
    *,
    run_id: str,
    task: str,
    target: str,
    target_original: str,
    classes: list[str],
    seeds: dict[str, int],
) -> str:
    """Source of `pipeline.py` for `model` (its unfitted copy is built by `build_model()`)."""
    source = estimator_source(model, depth=1, runtime_indent="    ")
    # isort order within the third-party section: plain imports, then sorted `from` imports
    third_party = [*THIRD_PARTY_PLAIN, *source.imports]
    env = Environment(loader=FileSystemLoader(TEMPLATES), autoescape=False,  # noqa: S701 - Python source, every value is a repr() literal
                      undefined=StrictUndefined, keep_trailing_newline=True)  # fmt: skip
    return env.get_template("pipeline.py.j2").render(
        run_id=run_id, run_id_literal=repr(run_id), task=repr(task), target=repr(target),
        target_original=repr(target_original), classes=repr(list(classes)),
        seeds=repr(dict(seeds)), imports=third_party,
        runtime_imports=source.runtime_imports,
        expression=source.expression,
    )  # fmt: skip
