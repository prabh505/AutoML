"""Page 1 — Upload (PRD §27.1, §3.2 stage 1, FR-ING-01, FR-ING-06, §27.3 Empty/Loading).

File uploader with the profile limit, the sample dataset cards, a privacy note and the demo-status
banner (slot busy / cold-start notice). Validation happens through `RunManager.validate_upload`;
a rejected file shows its E-code message and leaves nothing on disk.
"""

from __future__ import annotations

import time
from functools import partial
from typing import Any

import streamlit as st

from tabpilot.runtime.catalog import samples
from tabpilot.schemas import ExecutionProfileName, SemanticType
from tabpilot.ui import errors, services
from tabpilot.ui import state as sk
from tabpilot.ui.components.status import demo_banner
from tabpilot.ui.rerun import BUSY_TEXT, active_run
from tabpilot.ui.text import md_escape

EXTENSIONS = ["csv", "tsv", "txt", "parquet"]
PRIVACY_NOTE = (
    "Your file stays on this server. It is deleted when your run ends, after 30 idle minutes on "
    "the demo, or when you click “Delete my data now”. Nothing is sent to an LLM unless you "
    "agree to it on the next page, and raw rows are never sent."
)


def recheck_overrides(state: Any, upload_id: str) -> list[str]:
    """KI-066: a re-run keeps the column overrides, so each is checked again (FR-ING-04) on the
    new file; overrides for missing columns or values that no longer parse are removed.
    """
    manager = services.manager()
    names = {c.name for c in manager.upload_info(upload_id).metadata.columns}
    kept: dict[str, Any] = {}
    dropped: list[str] = []
    for column, o in state.get(sk.OVERRIDES, {}).items():
        if column not in names:
            dropped.append(f"{column}: not in the new file")
            continue
        stype = o.get("semantic_type")
        problem = manager.check_override(upload_id, column, SemanticType(stype)) if stype else None
        if problem:
            dropped.append(problem)
        else:
            kept[column] = o
    state[sk.OVERRIDES] = kept
    return dropped


def _accept(validate: Any, label: str) -> None:
    """Run one validation under the §27.3 loading state and move on to Configure."""
    state = st.session_state
    started = time.monotonic()
    with st.spinner("Reading file…", show_time=True):
        try:
            upload = validate()
        except Exception as exc:  # every failure is shown as an E-code message, no trace
            errors.remember(state, exc)
            return
    old = state.get(sk.UPLOAD_ID)
    if old and old != upload.run_id and not state.get(sk.RUN_ID):
        services.manager().discard_upload(old)  # a replaced, never-started upload
    dropped: list[str] = []
    if state.pop(sk.RERUN, None):
        state.pop(sk.TARGET_INFO, None)  # keep the choices; re-validate the target (KI-056)
        dropped = recheck_overrides(state, upload.run_id)
    else:
        sk.reset_choices(state)
    state[sk.UPLOAD_ID] = upload.run_id
    state[sk.DISPLAY_NAME] = upload.display_name
    if dropped:
        state[sk.NOTICE] = {"kind": "warning", "text": "Column changes that no longer fit the "
                            "new file were removed: " + "; ".join(dropped)}  # fmt: skip
        sk.go(state, "Configure")
        st.rerun()
    state[sk.NOTICE] = {"kind": "success",
                       "text": f"{label} read in {time.monotonic() - started:.1f} s: "
                               f"{upload.metadata.n_rows_raw:,} rows, "
                               f"{upload.metadata.n_columns} columns."}  # fmt: skip
    sk.go(state, "Configure")
    st.rerun()


def render() -> None:
    state = st.session_state
    settings = services.settings()
    st.title("TabPilot")
    st.write("Upload a table, pick what to predict, and get a validated model, a report and "
             "runnable code. Or start with one of the samples below.")  # fmt: skip
    demo_banner()
    if active_run(state):  # KI-057: never orphan a running analysis
        st.warning(BUSY_TEXT, icon=":material/hourglass_top:")
        st.button("Go to the Run page", on_click=sk.go, args=(state, "Run"), key="to_run")
        return

    limits = settings.limits
    hint = (f"Up to {limits.max_rows:,} rows and {limits.max_columns} columns on the "
            f"{settings.profile.value} profile.")  # fmt: skip
    uploaded = st.file_uploader(
        f"Upload a data file (CSV, TSV, TXT or Parquet, up to {limits.max_file_mb} MB)",
        type=EXTENSIONS,
        help=hint,
    )
    if uploaded is not None and state.get(sk.UPLOAD_TOKEN) != uploaded.file_id:
        state[sk.UPLOAD_TOKEN] = uploaded.file_id
        state.pop(sk.ERROR, None)
        state.pop(sk.SAMPLE_ID, None)
        _accept(lambda: services.manager().validate_upload(uploaded, uploaded.name), "File")
    errors.show(state.get(sk.ERROR))  # after the uploader: a rejection shows at once
    st.caption(PRIVACY_NOTE)

    st.subheader("Sample datasets")
    st.caption("Each sample is synthetic data generated by TabPilot (MIT license); it copies the "
               "columns of a well-known public dataset but none of its records.")  # fmt: skip
    for sample in samples():
        with st.container(border=True):
            st.markdown(f"**{md_escape(sample.title)}**")
            st.write(sample.description)
            st.caption(f"Target: {md_escape(sample.target)} · {sample.rows:,} rows · "
                       f"{sample.task.value}")  # fmt: skip
            if st.button("Use this sample", key=f"sample_{sample.sample_id}"):
                state.pop(sk.ERROR, None)
                state[sk.SAMPLE_ID] = sample.sample_id
                _accept(partial(services.manager().validate_sample, sample.sample_id), "Sample")
    if settings.profile == ExecutionProfileName.HOSTED:
        st.caption("If the app was asleep, the first page load can take a minute (cold start); "
                   "see About & Privacy.")  # fmt: skip
